import { createRequire } from "module";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2 });
await p.goto("http://localhost:8123/v4/");
await p.click("#btn-web"); await p.waitForTimeout(1200);
await p.evaluate(() => document.querySelector("#btn-task-close")?.click()); await p.waitForTimeout(600);
await p.evaluate(() => { setInputMode("voice"); $("#mic").classList.add("rec"); renderVoice(); });
await p.waitForTimeout(800);
const w = async () => p.evaluate(() => Math.round($("#voice-btn .vlabel").getBoundingClientRect().width));
const before = await w();
await p.evaluate(() => { $("#msg").value = "신분당선 동천역에서"; renderVoice(); });
await p.waitForTimeout(150);
const mid = await w();
await p.waitForTimeout(600);
const after = await w();
console.log({ before, mid, after });
await b.close();
